"""
src/metrics.py
==============
Evaluation metrics from Singla et al., "Explaining the Black-box Smoothly —
A Counterfactual Approach", Medical Image Analysis (2022).

Implemented metrics
-------------------
1. Counterfactual Validity (CV) score          — Eq. 11
2. Fréchet Inception Distance (FID) score      — Eq. 10  (normalised per paper)
3. Foreign-Object Preservation (FOP) score     — Eq. 12
4. Cardio-Thoracic Ratio (CTR)                 — cardiomegaly clinical metric
5. Score for normal CostoPhrenic recess (SCP)  — pleural effusion clinical metric

All functions follow the exact notation of the paper.

CHANGE FROM ORIGINAL: foreign_object_preservation() was returning a
degenerate 1.0/1.0/1.0 always — see its docstring for the root cause
and fix.

CHANGE (this revision): run_full_evaluation() now accepts optional
trained PPO policies (policy_n_to_p / policy_p_to_n, see
src/inference.py). When provided, counterfactuals are generated by
stepping the trained policy through its matching environment instead of
calling generator.generate_counterfactual directly with default
strength/guidance values — so reported CV/FID/FOP/CTR/SCP numbers
reflect the actual PPO-guided pipeline, not just the fine-tuned
generator on its own. If no policies are supplied, the old direct-
generator behaviour is preserved for backward compatibility / quick
generator-only sanity checks.
"""

