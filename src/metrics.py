_to_rgb = lambda t: t.repeat(1, 3, 1, 1) if t.shape[1] == 1 else t


# ─────────────────────────────────────────────────────────────────────────────
# 0. Shared group scan / scoring / config stamp
# ─────────────────────────────────────────────────────────────────────────────
#
# These three live here rather than in a caller because THREE entry points must
# agree on them exactly: run_full_evaluation, heldout_validation.py, and
# eval_main.py's sharded generate/reduce split. The split in particular is only
# correct if a shard process and the reduce process derive byte-identical Xn/Xp
# lists from the dataset — so there must be exactly one implementation of the
# scan, not a copy per caller that can drift.


def scan_groups(
    dataset,
    classifier,
    n_eval: int,
    device: str = config.DEVICE,
    batch_size: int = 32,
    tag: str = "metrics",
    allowed_indices=None,
) -> tuple[list[torch.Tensor], list[int], list[torch.Tensor], list[int]]:
    """
    Split the dataset into Xn (f(x) < 0.2) and Xp (f(x) > 0.8) using the
    GUIDANCE classifier, truncated to n_eval each.

    DETERMINISM CONTRACT — this function must return the same lists in the same
    order in every process, because eval_main.py --stage generate (running as N
    independent SLURM array tasks) and --stage reduce each call it and then
    index into the result. Two things guarantee that and must not change:

      * shuffle=False here, so the DataLoader walks the dataset in index order;
      * RSNACXRDataset.samples is built from a pandas groupby("patientId")
        (ingestion.py), whose index is sorted by key — so dataset index order is
        a stable function of patient ID, not of os.listdir order.

    Returning the dataset indices does NOT weaken that contract: they are read
    off the same shuffle=False walk that already fixes the order, so they are a
    function of it rather than a new source of variation.

    WHY THE INDICES MATTER. Returning tensors alone was the stated blocker for
    every annotation-based metric — with no index there is no way back to the
    patient, so no way to reach the radiologist-drawn lesion box for the image.
    That is what left "did the edit land on the pathology" unmeasurable, and it
    is the one question that separates a counterfactual from an adversarial
    perturbation. See lesion_hit_rate.

    `allowed_indices` restricts the scan to a fold (splits.py). Without it the
    groups are drawn from the whole dataset, including the images the generator
    was fine-tuned on and the policy did rollouts against.

    Returns (xn_list, xn_indices, xp_list, xp_indices) — tensors are
    (1, 1, H, W) CPU tensors; indices are ints into `dataset`, aligned
    element-wise with the tensors.
    """
    allowed = None if allowed_indices is None else set(int(i) for i in allowed_indices)
    print(
        f"[{tag}] scanning dataset for Xn / Xp (n_eval={n_eval})"
        + ("" if allowed is None else f" over {len(allowed)} held-out images")
        + " ..."
    )
    loader = DataLoader(
        dataset, batch_size=batch_size, shuffle=False,
        num_workers=config.DATALOADER_NUM_WORKERS,
    )

    # See config.EVAL_GROUP_SOURCE for why this is a knob and not a fix.
    by_label = getattr(config, "EVAL_GROUP_SOURCE", "classifier") == "label"
    if by_label:
        print(f"[{tag}] groups from the RADIOLOGIST LABEL, not f(x) — CV is NOT "
              f"comparable to classifier-selected runs (config.EVAL_GROUP_SOURCE)")

    xn_list, xp_list = [], []
    xn_idx,  xp_idx  = [], []
    base = 0
    with torch.no_grad():
        for x_batch, y_batch in loader:
            x_batch = x_batch.to(device)
            # Skip the forward pass entirely when the label decides membership.
            scores = None if by_label else classifier(_to_rgb(x_batch)).squeeze(-1)
            for i in range(len(x_batch)):
                gidx = base + i
                if allowed is not None and gidx not in allowed:
                    continue
                if by_label:
                    is_neg = float(y_batch[i].reshape(-1)[0].item()) < 0.5
                    is_pos = not is_neg
                else:
                    s = scores[i].item()
                    is_neg, is_pos = s < 0.2, s > 0.8
                if is_neg and len(xn_list) < n_eval:
                    xn_list.append(x_batch[i].unsqueeze(0).cpu())
                    xn_idx.append(gidx)
                elif is_pos and len(xp_list) < n_eval:
                    xp_list.append(x_batch[i].unsqueeze(0).cpu())
                    xp_idx.append(gidx)
            base += x_batch.shape[0]
            if len(xn_list) >= n_eval and len(xp_list) >= n_eval:
                break

    print(f"[{tag}] Xn={len(xn_list)}  Xp={len(xp_list)}")
    return xn_list, xn_idx, xp_list, xp_idx


def score_batch(
    x_list: list[torch.Tensor],
    classifier,
    device: str = config.DEVICE,
    batch_size: int = 32,
) -> torch.Tensor:
    """
    Score a list of (1,1,H,W) tensors -> (N,) float tensor on CPU.

    Batched rather than one image at a time: the metric phase scores four
    groups of up to 200 images each, and at batch size 1 that was 800 separate
    forward passes for no reason.
    """
    out = []
    with torch.no_grad():
        for i in range(0, len(x_list), batch_size):
            batch = torch.cat(x_list[i : i + batch_size]).to(device)
            out.append(classifier(_to_rgb(batch)).squeeze(-1).float().cpu())
    return torch.cat(out) if out else torch.empty(0)


def current_cfg_stamp() -> dict:
    """
    The config knobs that change what a counterfactual looks like.

    Written alongside every cached counterfactual (heldout_validation.py's
    cf_cache.pt, eval_main.py's cf_shard_*.pt) so a cache generated under one
    ablation arm can never be silently scored and reported as another. For the
    sharded eval it is also a consistency check ACROSS shards: eight array
    tasks that disagree on this stamp did not evaluate the same pipeline.

    Covers the generation objective (guidance ensemble, alpha weights), the
    spatial constraints (anchor, Grad-CAM mask, background lock), and the
    episode/diffusion budgets. Deliberately NOT covered: reward-shaping knobs
    that only affect PPO training, since the policies are loaded from a
    checkpoint here and reward is never computed.
    """
    return {
        # The BOOLEAN, not just the weight list. GUIDANCE_ENSEMBLE_WEIGHTS alone
        # is inert when this is False, so two runs that differ only by flipping
        # it produced entirely different guidance gradients while stamping
        # identically — the arms would have pooled with the drift guard silent,
        # which is the exact failure this stamp exists to prevent. Adding the key
        # means shards written before this change cannot be re-reduced (the
        # comparison in eval_main._load_shards is strict, deliberately); their
        # metrics are already computed, and their raw tensors stay readable by
        # paired_arm_test.py, which reads shards directly and not the stamp.
        "USE_GUIDANCE_ENSEMBLE": config.USE_GUIDANCE_ENSEMBLE,
        "GUIDANCE_ENSEMBLE_WEIGHTS": list(config.GUIDANCE_ENSEMBLE_WEIGHTS),
        "ANCHOR_TO_EPISODE_ORIGIN": config.ANCHOR_TO_EPISODE_ORIGIN,
        "USE_GRADCAM_MASK": config.USE_GRADCAM_MASK,
        "USE_SPARSITY_REWARD": config.USE_SPARSITY_REWARD,
        "BUDGET_T": config.BUDGET_T,
        "EDIT_BUDGET_L1": config.EDIT_BUDGET_L1,
        "ENV_REFINEMENT_PASSES": config.ENV_REFINEMENT_PASSES,
        # Added with the sharded-eval split: all four change the pixels a
        # counterfactual ends up with, so a shard written before/after a change
        # to any of them must not be mixed with one written after/before.
        "T_DIFF": config.T_DIFF,
        "FIXED_EPISODE_LENGTH": config.FIXED_EPISODE_LENGTH,
        "LOCK_BACKGROUND": config.LOCK_BACKGROUND,
        "ALPHA_CLS": config.ALPHA_CLS,
        "ALPHA_PRES": config.ALPHA_PRES,
        "ETA_OBJ": config.ETA_OBJ,
        # These three do not change how a counterfactual is GENERATED, but they
        # change WHICH IMAGES get one — and pooling shards that disagree on the
        # image set is exactly as wrong as pooling two ablation arms. The split
        # fields catch a fold that moved underneath a half-finished array.
        "EVAL_GROUP_SOURCE": getattr(config, "EVAL_GROUP_SOURCE", "classifier"),
        "USE_SPLIT": getattr(config, "USE_SPLIT", False),
        "SPLIT_SEED": getattr(config, "SPLIT_SEED", None),
        "TEST_FRAC": getattr(config, "TEST_FRAC", None),
    }


# ─────────────────────────────────────────────────────────────────────────────
# 1. Counterfactual Validity (CV)  —  Eq. 11
# ─────────────────────────────────────────────────────────────────────────────

def counterfactual_validity(
    f_x: torch.Tensor,
    f_xc: torch.Tensor,
    target: str,
    tau: float = 0.8,
    boundary: float = 0.5,
) -> float:
    """
    CV(X, Xc) = fraction of counterfactuals that move the classifier score
    by at least τ *in the intended direction* AND cross the decision
    boundary.

    This uses a stricter, paper-aligned criterion than a simple absolute change:
    the counterfactual must both (a) move in the desired direction by the
    required margin and (b) actually cross the decision boundary.

    Parameters
    ----------
    f_x     : (N,)  classifier scores on real images
    f_xc    : (N,)  classifier scores on counterfactual images
    target  : "positive" (n→p, score must rise) or
              "negative" (p→n, score must fall)
    tau     : margin threshold (paper uses 0.8)
    boundary: decision boundary the CF must cross (default 0.5)

    Returns
    -------
    float  CV score ∈ [0, 1], or NaN if the batch is empty/non-finite.
    """
    if f_x.shape != f_xc.shape:
        raise AssertionError("f_x and f_xc must have the same shape")

    f_x = f_x.detach().reshape(-1)
    f_xc = f_xc.detach().reshape(-1)

    if f_x.numel() == 0:
        return float("nan")

    finite_mask = torch.isfinite(f_x) & torch.isfinite(f_xc)
    if finite_mask.sum() == 0:
        return float("nan")

    f_x = f_x[finite_mask]
    f_xc = f_xc[finite_mask]

    if target == "positive":
        moved = (f_xc - f_x) >= tau
        crossed = (f_x <= boundary) & (f_xc > boundary)
    elif target == "negative":
        moved = (f_x - f_xc) >= tau
        crossed = (f_x >= boundary) & (f_xc < boundary)
    else:
        raise ValueError(f"target must be 'positive' or 'negative', got {target!r}")

    valid = moved & crossed
    return valid.float().mean().item()


# ─────────────────────────────────────────────────────────────────────────────
# 2. Fréchet Inception Distance (FID)  —  Eq. 10
# ─────────────────────────────────────────────────────────────────────────────

class _InceptionFeatureExtractor(nn.Module):
    """Penultimate-layer features of Inception-v3 (2048-d)."""

    def __init__(self, device: str):
        super().__init__()
        model = inception_v3(weights=Inception_V3_Weights.DEFAULT)
        model.fc = nn.Identity()      # drop final classifier
        model.aux_logits = False
        self.model = model.to(device).eval()
        self.device = device
        self.resize = T.Resize((299, 299), antialias=True)
        # FIX (Bug 1): Inception-v3 was trained on ImageNet-normalised inputs.
        # Feeding raw [0,1] pixel values (with no mean/std normalisation)
        # pushes every activation off-distribution and inflates FID for
        # every comparison, including real-vs-real. Normalise exactly like
        # the torchvision pretrained-weights preprocessing expects.
        self.normalize = T.Normalize(
            mean=[0.485, 0.456, 0.406],
            std=[0.229, 0.224, 0.225],
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """x : (B, 1, H, W) or (B, 3, H, W), values in [0, 1] → (B, 2048)"""
        if x.shape[1] == 1:
            x = x.repeat(1, 3, 1, 1)
        x = self.resize(x)
        x = self.normalize(x)
        with torch.no_grad():
            feat = self.model(x.to(self.device))
        return feat.cpu()


class _XRVFeatureExtractor(nn.Module):
    """
    Penultimate-layer features (1024-d) of TorchXRayVision's DenseNet-121.

    Default weights ("densenet121-res224-rsna") are trained specifically
    on the RSNA Pneumonia Detection Challenge dataset — the same source
    distribution as this project's cxr-data-set. This gives a feature
    space that's directly sensitive to pneumonia-relevant visual patterns,
    unlike ImageNet-pretrained Inception-v3 or the broader multi-dataset
    "-all" xrv weights.

    Other useful weight options (pass via `weights=`):
      "densenet121-res224-all"  -> joint NIH+CheXpert+PadChest+MIMIC+RSNA,
                                    broader but less pneumonia-specific
      "densenet121-res224-nih"  -> NIH ChestX-ray14 only
      "densenet121-res224-chex" -> CheXpert only

    Since this project already depends on torchxrayvision for the PSPNet
    segmenter, this adds no new dependency.
    """

    def __init__(self, device: str, weights: str = "densenet121-res224-rsna"):
        super().__init__()
        model = xrv.models.DenseNet(weights=weights)
        self.model = model.to(device).eval()
        self.device = device
        self.input_size = 224  # xrv DenseNet default input resolution

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """
        x : (B, 1, H, W) or (B, 3, H, W), values expected in [0, 1]
            (single-channel grayscale CXR — extra channels are averaged down,
            since xrv models are single-channel).
        Returns (B, 1024) penultimate-layer features.
        """
        if x.shape[1] == 3:
            x = x.mean(dim=1, keepdim=True)

        # xrv models expect inputs scaled to roughly [-1024, 1024] (their
        # "normalize" convention), not raw [0,1]. If your tensors are
        # already in [0,1] from the VAE decoder, rescale like this:
        x_xrv = x * 2048.0 - 1024.0

        if x_xrv.shape[-1] != self.input_size or x_xrv.shape[-2] != self.input_size:
            x_xrv = F.interpolate(
                x_xrv, size=(self.input_size, self.input_size),
                mode="bilinear", align_corners=False,
            )

        with torch.no_grad():
            feat = self.model.features(x_xrv.float().to(self.device))
            feat = F.adaptive_avg_pool2d(feat, (1, 1)).flatten(1)  # (B, 1024)

        return feat.cpu()


def _compute_activation_stats(
    images: list[torch.Tensor],
    extractor: nn.Module,
    batch_size: int = 16,
) -> tuple[np.ndarray, np.ndarray]:
    """Return (μ, Σ) of Inception activations for a list of images."""
    feats = []
    for i in range(0, len(images), batch_size):
        batch = torch.cat(images[i : i + batch_size], dim=0)
        feats.append(extractor(batch))
    feats = torch.cat(feats, dim=0).numpy()
    mu    = feats.mean(axis=0)
    sigma = np.cov(feats, rowvar=False)
    return mu, sigma


def frechet_inception_distance(
    X_real: list[torch.Tensor],
    X_cf:   list[torch.Tensor],
    device: str = config.DEVICE,
    batch_size: int = 16,
    reference_fid: Optional[float] = None,
    eps: float = 1e-6,
    backbone: str = "xrv",
    extractor: Optional[nn.Module] = None,
) -> float:
    """
    FID(X, Xc) as defined in Eq. 10.

    Paper normalises all FID scores w.r.t. the best method (CycleGAN = 1).
    Pass ``reference_fid`` (the CycleGAN FID) to get the normalised value.

    Parameters
    ----------
    X_real : list of (1,1,H,W) tensors — real images
    X_cf   : list of (1,1,H,W) tensors — counterfactual images
    reference_fid : FID of the reference/best method for normalisation
    eps    : regularisation added to the covariance diagonals before
             sqrtm. FIX (Bug 2): with N samples < 2048 feature dims,
             the covariance matrices are rank-deficient/singular, which
             makes scipy.linalg.sqrtm numerically unstable (near-zero
             eigenvalues produce spurious imaginary/large real components).
             This is the same fix used by the standard pytorch-fid
             implementation.

    backbone : "xrv"       -> TorchXRayVision DenseNet-121 (1024-d),
                              pretrained on chest X-rays. Domain-appropriate,
                              recommended default for this project.
               "inception" -> ImageNet Inception-v3 (2048-d), the classic
                              FID backbone. Kept for comparability with
                              natural-image FID literature / papers that
                              report vanilla FID.
    extractor : pre-built feature extractor to reuse across multiple FID
                calls (e.g. one built once in run_full_evaluation and
                shared between the negative-group and positive-group FID
                calls, instead of reloading weights twice). If None, a
                fresh extractor is built internally using `backbone`.

    Note
    ----
    FID estimates are only stable with large sample sizes (rule of thumb:
    N >> feature dim). With N ~ 100-200 (typical after filtering into
    Xn/Xp groups) expect high variance in this number even after the fixes
    above — increase n_eval wherever your compute budget allows.
    """
    if extractor is None:
        if backbone == "xrv":
            extractor = _XRVFeatureExtractor(device)
        elif backbone == "inception":
            extractor = _InceptionFeatureExtractor(device)
        else:
            raise ValueError(f"Unknown backbone '{backbone}', expected 'xrv' or 'inception'")
    mu1, sigma1 = _compute_activation_stats(X_real, extractor, batch_size)
    mu2, sigma2 = _compute_activation_stats(X_cf,   extractor, batch_size)

    # FIX (Bug 2): regularise before sqrtm to avoid singular-matrix blowups
    sigma1 = sigma1 + np.eye(sigma1.shape[0]) * eps
    sigma2 = sigma2 + np.eye(sigma2.shape[0]) * eps

    diff = mu1 - mu2
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        covmean = linalg.sqrtm(sigma1 @ sigma2)
    if np.iscomplexobj(covmean):
        # residual imaginary component should be ~0 after regularisation;
        # if it isn't, something's still off numerically — warn loudly
        max_imag = np.max(np.abs(covmean.imag))
        if max_imag > 1e-3:
            print(f"[metrics] WARNING: sqrtm returned large imaginary "
                  f"component ({max_imag:.4f}) — FID may be unreliable. "
                  f"Consider increasing n_eval or eps.")
        covmean = covmean.real

    fid = float(diff @ diff + np.trace(sigma1 + sigma2 - 2.0 * covmean))

    if reference_fid is not None and reference_fid > 0:
        fid = fid / reference_fid

    return fid


# ─────────────────────────────────────────────────────────────────────────────
# 3. Foreign-Object Preservation (FOP)  —  Eq. 12
# ─────────────────────────────────────────────────────────────────────────────

class _XRVSupportDeviceDetector(nn.Module):
    """
    Detects presence of support devices (pacemakers, ECG leads, chest
    tubes, central lines, etc.) using TorchXRayVision's DenseNet-121.

    "Support Devices" is one of CheXpert's 14 original pathology labels,
    and models trained on (or including) CheXpert expose it directly as
    an output head. This gives a real, properly-calibrated [0,1]
    presence probability, trained specifically on chest X-rays for
    exactly this purpose — unlike a COCO-pretrained object detector,
    which has never seen a support device in training.

    Requires zero additional fine-tuning or compute: torchxrayvision is
    already a dependency of this project (used for the PSPNet segmenter),
    so this just loads a second pretrained xrv model.

    weights options that include "Support Devices" (check
    model.pathologies if using a different weight set):
      "densenet121-res224-all"  -> joint NIH+CheXpert+PadChest+MIMIC+RSNA
                                    (recommended: broadest training data)
      "densenet121-res224-chex" -> CheXpert only (where the label originates)
    """

    def __init__(self, device: str, weights: str = "densenet121-res224-chex"):
        super().__init__()
        model = xrv.models.DenseNet(weights=weights)
        self.model      = model.to(device).eval()
        self.device     = device
        self.input_size = 224

        # No pretrained xrv DenseNet classifier actually exposes a
        # "Support Devices" output head — that label only exists in xrv's
        # dataset label-loading code, not in any shipped weight set. Rather
        # than crash, flag the detector as unavailable so FOP can be
        # gracefully skipped (reported as N/A) by the caller.
        self.available = "Support Devices" in model.pathologies
        self.sd_idx    = model.pathologies.index("Support Devices") if self.available else None
        if not self.available:
            print(
                f"[metrics] WARNING: 'Support Devices' head absent from "
                f"weights='{weights}' (available heads: {model.pathologies}). "
                f"FOP will be skipped (reported as N/A)."
            )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """
        x : (B, 1, H, W) or (B, 3, H, W), values in [0, 1]
        Returns (B,) support-device presence probability in [0, 1].
        """
        if x.shape[1] == 3:
            x = x.mean(dim=1, keepdim=True)

        x_xrv = x * 2048.0 - 1024.0
        if x_xrv.shape[-1] != self.input_size or x_xrv.shape[-2] != self.input_size:
            x_xrv = F.interpolate(
                x_xrv, size=(self.input_size, self.input_size),
                mode="bilinear", align_corners=False,
            )

        with torch.no_grad():
            # xrv models output already-calibrated [0,1] probabilities
            # per pathology (sigmoid applied internally), not raw logits.
            probs = self.model(x_xrv.float().to(self.device))
            sd_prob = probs[:, self.sd_idx]

        return sd_prob.cpu()


def foreign_object_preservation(
    fo_detector,
    X_real: list[torch.Tensor],
    X_cf:   list[torch.Tensor],
    fo_threshold: float = 0.5,
    device: str = config.DEVICE,
) -> float:
    """
    FOP(X, Xc) = fraction of images where FO is detected in BOTH
                 the real image AND its counterfactual.

    Only images where a detection probability > fo_threshold is
    considered (paper Eq. 12).

    HISTORY:
      v1 thresholded a raw YOLO backbone feature-vector L2 norm against
      fo_threshold=0.5 — norms are routinely tens-to-hundreds, so this
      was true for ~every image, giving a degenerate 1.0 always.
      v2 fixed the threshold-space bug by using the full YOLO detection
      head instead, but yolov8n.pt is COCO-pretrained (everyday objects),
      not trained on medical support devices at all.
      v3 (this version) replaces YOLO entirely with a TorchXRayVision
      DenseNet-121 classifier that has a dedicated, CheXpert-trained
      "Support Devices" output — a properly domain-matched detector,
      requiring no fine-tuning since it's already pretrained for exactly
      this label.

    Parameters
    ----------
    fo_detector   : _XRVSupportDeviceDetector (or any nn.Module returning
                    a (B,) or scalar [0,1] support-device probability per
                    image when called on a (1,C,H,W) tensor)
    X_real        : list of (1,1,H,W) tensors
    X_cf          : list of (1,1,H,W) tensors
    fo_threshold  : detection probability threshold (paper: 0.5)

    Returns
    -------
    float — FOP score ∈ [0, 1]
    """
    assert len(X_real) == len(X_cf)

    # Detector has no support-device head in this xrv version -> skip FOP.
    if getattr(fo_detector, "available", True) is False:
        return None

    preserved, total = 0, 0
    for x, xc in zip(X_real, X_cf):
        with torch.no_grad():
            conf_real = fo_detector(x.to(device)).item()
            conf_cf   = fo_detector(xc.to(device)).item()

        fo_in_real = conf_real > fo_threshold
        fo_in_cf   = conf_cf   > fo_threshold

        if fo_in_real:
            total     += 1
            preserved += int(fo_in_cf)

    return preserved / max(total, 1)


# ─────────────────────────────────────────────────────────────────────────────
# 3b. Identity Preservation (IP)  —  model-free replacement for FOP
# ─────────────────────────────────────────────────────────────────────────────
#
# WHY THIS EXISTS
#   FOP (Eq. 12) needs a foreign-object / support-device detector. Singla et
#   al. trained a custom Fast R-CNN on ~300 manually-annotated images per
#   object (private data, 80% acc, never released), and no torchxrayvision
#   classifier exposes a "Support Devices" head. So a faithful FOP is not
#   computable offline.
#
#   IP measures what FOP is actually a proxy for: "is patient-specific,
#   non-pathology content preserved between the real image and its
#   counterfactual?" It needs NO extra model and NO downloads — pure
#   torch — so it runs anywhere the rest of the eval runs.
#
#   Two complementary, self-contained scores (both in [0,1], higher = better
#   preservation, both = 1.0 for an identical pair):
#     - ms_ssim : multi-scale structural similarity. Global structural/
#                 anatomical identity retained across scales.
#     - hf_corr : correlation of high-pass-filtered images. Foreign objects
#                 (tubes, lines, wires, pacemaker leads) are thin, high-
#                 contrast, high-frequency structures — this score is a
#                 direct proxy for whether those fine details survive.


def _gaussian_window(window_size: int, sigma: float, device) -> torch.Tensor:
    """2-D Gaussian conv kernel, shape (1,1,window_size,window_size)."""
    coords = torch.arange(window_size, dtype=torch.float32, device=device)
    coords -= (window_size - 1) / 2.0
    g = torch.exp(-(coords ** 2) / (2.0 * sigma ** 2))
    g = g / g.sum()
    kernel_2d = g[:, None] @ g[None, :]
    return kernel_2d[None, None, :, :]


def _ssim_maps(x: torch.Tensor, y: torch.Tensor, window: torch.Tensor,
               data_range: float = 1.0):
    """Per-image mean SSIM and contrast-structure (cs) values. x,y: (B,1,H,W)."""
    pad = window.shape[-1] // 2
    filt = lambda t: F.conv2d(t, window, padding=pad)

    mu_x, mu_y = filt(x), filt(y)
    mu_x2, mu_y2, mu_xy = mu_x * mu_x, mu_y * mu_y, mu_x * mu_y
    sigma_x2 = filt(x * x) - mu_x2
    sigma_y2 = filt(y * y) - mu_y2
    sigma_xy = filt(x * y) - mu_xy

    C1 = (0.01 * data_range) ** 2
    C2 = (0.03 * data_range) ** 2
    cs_map   = (2 * sigma_xy + C2) / (sigma_x2 + sigma_y2 + C2)
    ssim_map = ((2 * mu_xy + C1) / (mu_x2 + mu_y2 + C1)) * cs_map
    return ssim_map.mean(dim=[1, 2, 3]), cs_map.mean(dim=[1, 2, 3])


def _ms_ssim(x: torch.Tensor, y: torch.Tensor,
             window_size: int = 11, sigma: float = 1.5,
             data_range: float = 1.0) -> torch.Tensor:
    """
    Multi-scale SSIM, per image -> (B,). Number of scales is adapted to the
    image size so small images don't over-downsample.
    """
    weights_full = torch.tensor(
        [0.0448, 0.2856, 0.3001, 0.2363, 0.1333], device=x.device
    )
    # Each downsample halves H,W; the coarsest scale must still be >= window.
    min_hw = min(x.shape[-2], x.shape[-1])
    max_levels = max(1, int(math.floor(math.log2(min_hw / window_size))) + 1)
    levels = min(len(weights_full), max_levels)
    weights = weights_full[:levels]
    weights = weights / weights.sum()  # renormalise if fewer scales

    window = _gaussian_window(window_size, sigma, x.device)
    mssim, mcs = [], []
    for i in range(levels):
        ssim_i, cs_i = _ssim_maps(x, y, window, data_range)
        mssim.append(ssim_i)
        mcs.append(cs_i)
        if i < levels - 1:
            x = F.avg_pool2d(x, kernel_size=2)
            y = F.avg_pool2d(y, kernel_size=2)

    mcs   = torch.clamp(torch.stack(mcs,   dim=0), min=1e-6)   # (levels, B)
    mssim = torch.clamp(torch.stack(mssim, dim=0), min=1e-6)
    pow_cs   = mcs[:-1] ** weights[:-1, None]
    pow_ssim = mssim[-1] ** weights[-1]
    return pow_cs.prod(dim=0) * pow_ssim                        # (B,)


def _hf_correlation(x: torch.Tensor, y: torch.Tensor,
                    window_size: int = 11, sigma: float = 1.5) -> torch.Tensor:
    """
    Pearson correlation of high-pass-filtered images, per image -> (B,),
    rescaled from [-1,1] to [0,1]. High-pass = image minus Gaussian blur,
    isolating thin high-contrast structures (tubes/lines/leads).
    """
    window = _gaussian_window(window_size, sigma, x.device)
    pad = window_size // 2
    hx = x - F.conv2d(x, window, padding=pad)
    hy = y - F.conv2d(y, window, padding=pad)

    hx = hx.flatten(1)
    hy = hy.flatten(1)
    hx = hx - hx.mean(dim=1, keepdim=True)
    hy = hy - hy.mean(dim=1, keepdim=True)
    num = (hx * hy).sum(dim=1)
    den = torch.sqrt((hx ** 2).sum(dim=1) * (hy ** 2).sum(dim=1)) + 1e-8
    corr = num / den                                            # (B,) in [-1,1]
    return (corr + 1.0) / 2.0                                   # -> [0,1]


def identity_preservation(
    X_real: list[torch.Tensor],
    X_cf:   list[torch.Tensor],
    device: str = config.DEVICE,
) -> dict:
    """
    Model-free FOP replacement. Both inputs are lists of paired (1,C,H,W)
    tensors in [0,1]; real[i] corresponds to cf[i].

    Returns dict(ms_ssim=<float>, hf_corr=<float>), each the mean over the
    paired set, both in [0,1] (higher = better patient-detail preservation).
    """
    assert len(X_real) == len(X_cf)
    if len(X_real) == 0:
        return dict(ms_ssim=None, hf_corr=None)

    ms_vals, hf_vals = [], []
    for x, xc in zip(X_real, X_cf):
        x  = x.to(device).float()
        xc = xc.to(device).float()
        if x.shape[1] == 3:
            x = x.mean(dim=1, keepdim=True)
        if xc.shape[1] == 3:
            xc = xc.mean(dim=1, keepdim=True)
        if xc.shape[-2:] != x.shape[-2:]:
            xc = F.interpolate(xc, size=x.shape[-2:],
                               mode="bilinear", align_corners=False)
        with torch.no_grad():
            ms_vals.append(_ms_ssim(x, xc).mean().item())
            hf_vals.append(_hf_correlation(x, xc).mean().item())

    return dict(ms_ssim=float(np.mean(ms_vals)),
                hf_corr=float(np.mean(hf_vals)))


# ─────────────────────────────────────────────────────────────────────────────
# 3c. Edit concentration  —  model-free locality / adversarial discriminator
# ─────────────────────────────────────────────────────────────────────────────

def edit_concentration(
    X_real: list[torch.Tensor],
    X_cf:   list[torch.Tensor],
    top_frac: float = 0.05,
) -> dict:
    """
    Fraction of total |x_cf - x| mass held by the top `top_frac` of pixels,
    averaged over pairs. Needs no model and no downloads.

    WHY THIS IS HERE
    ----------------
    A semantic edit and an adversarial perturbation are separated by their
    L0/L-inf profile, not by their magnitude. A focal consolidation is
    large-amplitude over a small support and concentrates most of its mass in
    a few pixels; an adversarial perturbation is small-amplitude over a wide
    support and spreads mass almost uniformly. Uniform change scores exactly
    `top_frac` (0.05), so that value is the noise floor and >~0.5 is focal.

    Calibration on synthetic pairs: a diffuse edit (75% of pixels, MAE 0.037 —
    close to what this pipeline measured) scores 0.067; a compact 12x12 patch
    scores 1.000. v1 counterfactuals scored 0.282 (n→p) / 0.297 (p→n), i.e.
    partly localized but mostly diffuse.

    Also returns mean L1 and the fraction of pixels moved by >0.01, matching
    the "% changed" figure diff_viz prints, so the numbers are directly
    comparable to the counterfactual_diff plots.

    Shared with heldout_validation.py, which imports it from here so both
    reports compute concentration exactly the same way.
    """
    concs, maes, fracs = [], [], []
    for x, xc in zip(X_real, X_cf):
        d = (xc.float() - x.float()).abs().flatten()
        total = d.sum()
        if total <= 0:
            continue
        k = max(1, int(round(top_frac * d.numel())))
        topk = torch.topk(d, k).values.sum()
        concs.append((topk / total).item())
        maes.append(d.mean().item())
        fracs.append((d > 0.01).float().mean().item())

    return dict(
        concentration=float(np.mean(concs)) if concs else float("nan"),
        uniform_baseline=top_frac,
        mae=float(np.mean(maes)) if maes else float("nan"),
        frac_changed=float(np.mean(fracs)) if fracs else float("nan"),
    )


# ─────────────────────────────────────────────────────────────────────────────
# 3d. Lesion Hit Rate (LHR)  —  the ground-truth localisation metric
# ─────────────────────────────────────────────────────────────────────────────

def lesion_hit_rate(
    X_real: list[torch.Tensor],
    X_cf:   list[torch.Tensor],
    indices: list[int],
    dataset,
) -> dict:
    """
    Share of the edit's absolute-difference mass that falls INSIDE the
    radiologist-drawn lesion annotation, against the annotation's area share as
    the chance baseline.

    WHY THIS IS THE METRIC THAT MATTERS
    -----------------------------------
    Every other score here is computed against a model. CV asks a classifier,
    FID asks a feature extractor, CTR and SCP ask a segmenter and a COCO
    backbone. All of them can be satisfied by an edit that changes the right
    numbers for the wrong reason — which is exactly what held-out validation
    caught: counterfactuals the guidance model accepted 99.5% of the time were
    accepted 0-8% of the time by an independent one.

    This metric asks a human instead. RSNA ships 9,555 opacity boxes drawn by
    radiologists; `lesion_hit_rate` measures whether the pixels the system
    changed are the pixels a radiologist circled. No classifier can be fooled
    into agreeing.

    INTERPRETATION
    --------------
      hit_rate  share of |x_cf - x| inside the annotation
      null      the annotation's share of image area — what a spatially
                UNIFORM edit scores, i.e. the chance floor
      lift      hit_rate / null. 1.0 = indistinguishable from an edit that
                ignores the annotation entirely. >1 = preferentially on the
                lesion. This is the number to report.

    The paired t-test is on (hit_rate - null) per image, so it answers "does the
    edit land on the lesion more than chance", which is the actual claim.

    ONLY DEFINED FOR THE p->n DIRECTION, AND THAT IS NOT A LIMITATION TO PAPER
    OVER. p->n starts from a POSITIVE image, which has an annotation, and the
    edit is supposed to remove what is inside it — so ground truth exists.
    n->p starts from a NEGATIVE image, which has no annotation because there is
    no finding to draw, so there is no ground-truth answer to "where should the
    synthesized opacity go". Computing something here anyway would be inventing
    a target. Callers must pass the positive-source group; run_full_evaluation
    reports the n->p direction as not-applicable rather than as a number.

    Skips images whose annotation is empty or covers the whole frame (a
    degenerate box gives a null of 0 or 1 and an undefined lift).
    """
    if not hasattr(dataset, "lesion_mask"):
        return {
            "_omitted": (
                f"dataset {type(dataset).__name__} exposes no lesion_mask(idx); "
                f"this domain has no lesion annotation to score against"
            )
        }
    if indices is None:
        return {"_omitted": "dataset indices unavailable (shards predate index threading)"}

    hits, nulls, lifts = [], [], []
    n_no_annotation = 0

    for x, xc, idx in zip(X_real, X_cf, indices):
        mask = dataset.lesion_mask(int(idx)).to(torch.float32)     # (1, H, W)
        null = float(mask.mean().item())
        if null <= 0.0 or null >= 1.0:
            n_no_annotation += 1
            continue

        # Collapse channels before masking so a multi-channel image contributes
        # one difference map, matching the single-channel annotation.
        d = (xc.float() - x.float()).abs()
        while d.dim() > 3:
            d = d.squeeze(0)
        if d.shape[0] > 1:
            d = d.mean(dim=0, keepdim=True)

        total = float(d.sum().item())
        if total <= 0:
            continue                      # identity edit: hit rate undefined

        inside = float((d * mask).sum().item())
        hit = inside / total
        hits.append(hit)
        nulls.append(null)
        lifts.append(hit / null)

    if not hits:
        return {
            "_omitted": (
                f"no scorable pairs: {n_no_annotation} of {len(X_real)} images had "
                f"no usable lesion annotation"
            )
        }

    # Imported here rather than at module scope to match run_full_evaluation,
    # which does the same — scipy is a heavy import for a module that is loaded
    # by every entry point.
    from scipy import stats as scipy_stats

    delta = np.array(hits) - np.array(nulls)
    # ttest_rel needs >1 sample and a non-zero spread; a constant delta (every
    # box identical) would divide by zero.
    if len(delta) > 1 and float(delta.std()) > 0:
        t_stat, p_val = scipy_stats.ttest_rel(np.array(hits), np.array(nulls))
    else:
        t_stat, p_val = float("nan"), float("nan")

    return dict(
        hit_rate=float(np.mean(hits)),      std_hit_rate=float(np.std(hits)),
        null_baseline=float(np.mean(nulls)), std_null=float(np.std(nulls)),
        lift=float(np.mean(lifts)),          std_lift=float(np.std(lifts)),
        mean_delta=float(delta.mean()),      std_delta=float(delta.std()),
        t=float(t_stat), p=float(p_val),
        n_pairs=len(hits),
        n_without_annotation=n_no_annotation,
    )


# ─────────────────────────────────────────────────────────────────────────────
# 4. Cardio-Thoracic Ratio (CTR)  —  cardiomegaly clinical metric
# ─────────────────────────────────────────────────────────────────────────────

def compute_ctr_batch(
    x_list: list[torch.Tensor],
    seg_net: nn.Module,
    lung_channel_idx: list[int],
    heart_channel_idx: int,
    device: str = config.DEVICE,
    seg_input_size: int = config.SEG_INPUT_SIZE,
    batch_size: int = 16,
) -> list[float]:
    """
    Cardio-Thoracic Ratio over a list of images -> list[float], NaN where a
    mask came out empty.

    Batched because the metric phase runs CTR over four groups of up to 200
    images each, and the PSPNet forward is at SEG_INPUT_SIZE=512 — 800 of those
    one at a time was tens of minutes of pure launch overhead. Only the
    segmentation forward is batched; the per-image column spans below are cheap
    numpy on an already-thresholded mask.

    See compute_ctr for the definition and the Chamveha et al. (2020) reference.
    """
    out: list[float] = []
    for i in range(0, len(x_list), batch_size):
        chunk = torch.cat(x_list[i : i + batch_size]).to(device)   # (b,1,H,W)
        H, W  = chunk.shape[-2:]

        x_xrv = chunk * 2048.0 - 1024.0
        if (H, W) != (seg_input_size, seg_input_size):
            x_xrv = F.interpolate(
                x_xrv, size=(seg_input_size, seg_input_size),
                mode="bilinear", align_corners=False,
            )

        with torch.no_grad():
            seg_out = seg_net(x_xrv.float())          # (b, n_classes, H', W')
            lung = (torch.sigmoid(seg_out[:, lung_channel_idx]).amax(dim=1) > 0.5)
            heart = (torch.sigmoid(seg_out[:, heart_channel_idx]) > 0.5)
        lung_np  = lung.cpu().numpy()                 # (b, H', W')
        heart_np = heart.cpu().numpy()                # (b, H', W')

        for b in range(lung_np.shape[0]):
            lung_mask, heart_mask = lung_np[b], heart_np[b]
            if lung_mask.sum() == 0 or heart_mask.sum() == 0:
                out.append(float("nan"))
                continue
            heart_cols    = np.where(heart_mask.any(axis=0))[0]
            cardiac_diam  = float(heart_cols[-1] - heart_cols[0]) if len(heart_cols) >= 2 else 0.0
            lung_cols     = np.where(lung_mask.any(axis=0))[0]
            thoracic_diam = float(lung_cols[-1] - lung_cols[0]) if len(lung_cols) >= 2 else 1.0
            out.append(cardiac_diam / (thoracic_diam + 1e-8))
    return out


def compute_ctr(
    x: torch.Tensor,
    seg_net: nn.Module,
    lung_channel_idx: list[int],
    heart_channel_idx: int,
    device: str = config.DEVICE,
    seg_input_size: int = config.SEG_INPUT_SIZE,
) -> float:
    """
    Cardio-Thoracic Ratio = cardiac_diameter / thoracic_diameter.

    Paper: CTR > 0.5 indicates cardiomegaly.
    We follow Chamveha et al. (2020) as referenced in the paper:
      - cardiac diameter  = horizontal span of the heart mask
      - thoracic diameter = horizontal span of the lung mask

    Single-image wrapper over compute_ctr_batch, kept because other callers
    (and the paper's notation) work one image at a time. The metric suite uses
    the batched form.

    Parameters
    ----------
    x                 : (1, 1, H, W) CXR image, values in [0, 1]
    seg_net           : torchxrayvision PSPNet
    lung_channel_idx  : [left_lung_ch, right_lung_ch]
    heart_channel_idx : channel index for heart in seg_net.targets

    Returns
    -------
    float — CTR value (or np.nan if masks are empty)
    """
    return compute_ctr_batch(
        [x], seg_net, lung_channel_idx, heart_channel_idx, device, seg_input_size
    )[0]


# ─────────────────────────────────────────────────────────────────────────────
# 5. Score for normal CostoPhrenic recess (SCP)  —  pleural effusion metric
# ─────────────────────────────────────────────────────────────────────────────

def compute_scp_batch(
    x_list: list[torch.Tensor],
    obj_det,
    device: str = config.DEVICE,
    batch_size: int = 16,
) -> list[float]:
    """
    SCP proxy over a list of images -> list[float]. Batched form of
    compute_scp (see it for the definition and its caveats — the proxy is
    known to saturate, and run_full_evaluation flags that).

    Same motivation as compute_ctr_batch: 800 single-image YOLO forwards in the
    metric phase for no reason.
    """
    out: list[float] = []
    for i in range(0, len(x_list), batch_size):
        chunk = torch.cat(x_list[i : i + batch_size]).to(device)
        H = chunk.shape[-2]
        lower_third = chunk[:, :, int(2 * H / 3) :, :]
        x3 = _to_rgb(lower_third)
        with torch.no_grad():
            feat = obj_det(x3)                             # (b, D)
            norms = feat.norm(dim=-1)                      # (b,)
            scps = torch.sigmoid(-norms.float() / 50.0)
        out.extend(scps.cpu().tolist())
    return out


def compute_scp(
    x: torch.Tensor,
    obj_det,
    device: str = config.DEVICE,
) -> float:
    """
    Score for detecting a healthy (normal) CostoPhrenic recess.

    In the paper, SCP is computed by a dedicated CP-recess object detector
    trained on MIMIC-CXR. We approximate it here using the YOLOv8 feature
    extractor: a high-entropy, low-norm feature response in the lower-lobe
    region corresponds to the absence of blunting (healthy CP recess ≈ high SCP).

    The returned value is in [0, 1] (sigmoid-normalised).

    Parameters
    ----------
    x       : (1, 1, H, W) CXR image
    obj_det : YOLOv8FeatureExtractor

    Returns
    -------
    float — SCP proxy score
    """
    # Single-image wrapper over compute_scp_batch. The proxy itself is
    # unchanged: low feature-norm in the lower lobe = healthy (no fluid, so
    # high SCP).
    return compute_scp_batch([x], obj_det, device)[0]


# ─────────────────────────────────────────────────────────────────────────────
# 6. Full evaluation suite  —  mirrors Table 1 of the paper
# ─────────────────────────────────────────────────────────────────────────────

def run_full_evaluation(
    dataset,
    classifier,
    generator,
    seg_net,
    lung_channel_idx: list[int],
    obj_det,
    n_eval: int = 200,
    tau_cv: float = 0.8,
    fo_threshold: float = 0.5,
    ckpt_dir: str = config.CKPT_DIR,
    device: str = config.DEVICE,
    fid_backbone: str = "xrv",
    policy_n_to_p=None,
    policy_p_to_n=None,
    deterministic_policy: bool = True,
    xn_list: Optional[list[torch.Tensor]] = None,
    xp_list: Optional[list[torch.Tensor]] = None,
    xc_np: Optional[list[torch.Tensor]] = None,
    xc_pn: Optional[list[torch.Tensor]] = None,
    clinical_metrics: tuple[str, ...] = ("CTR", "SCP"),
    # Dataset indices aligned with xn_list / xp_list. Required for LHR, which is
    # the only metric here scored against ground truth rather than a model.
    xn_idx: Optional[list[int]] = None,
    xp_idx: Optional[list[int]] = None,
    allowed_indices=None,
) -> dict:
    """
    Run the complete evaluation protocol from Singla et al. (2022).

    Splits the dataset into:
      Xn  — negative group: f(x) < 0.2  (predicted normal)
      Xp  — positive group: f(x) > 0.8  (predicted abnormal)

    Then generates:
      Xc_n→p  — counterfactuals from Xn with c = 1.0  (push toward abnormal)
      Xc_p→n  — counterfactuals from Xp with c = 0.0  (push toward normal)

    Computes for each split:
      - CV score
      - FID score  (negative group and positive group separately, as in Table 1)
      - FOP score
      - CTR statistics (mean ± std, paired t-test Δ)
      - SCP statistics (mean ± std, paired t-test Δ)

    Parameters
    ----------
    n_eval : number of images to sample from each group (capped by group size).
             NOTE: FID is unstable at small N (see frechet_inception_distance
             docstring). Prefer n_eval >= 1000 if your generation budget allows.
    fid_backbone : "xrv" (default, recommended for CXR data) or "inception".
             See frechet_inception_distance docstring for details. Built
             once here and reused for both the negative-group and
             positive-group FID calls to avoid loading weights twice.
    policy_n_to_p, policy_p_to_n : src.inference.DirectionalPolicy | None
             If provided, counterfactuals are generated by stepping the
             trained PPO policy through its environment
             (src.inference.generate_batch_with_policy) instead of calling
             generator.generate_counterfactual directly with default
             strength/guidance values. This makes the reported
             CV/FID/FOP/CTR/SCP numbers reflect what the trained PPO
             pipeline actually produces, rather than the fine-tuned
             generator alone. If None (default), falls back to the old
             direct-generator path — useful for a quick generator-only
             sanity check without needing trained policies loaded.
    deterministic_policy : bool
             Passed through to generate_batch_with_policy when policies
             are provided. True (default) uses the policy's mean action
             for reproducible eval numbers.
    xn_list, xp_list, xc_np, xc_pn : list[Tensor] | None
             PRECOMPUTED path. Supply all four to skip both the group scan and
             counterfactual generation and go straight to scoring — this is
             what eval_main.py --stage reduce uses to compute metrics from
             counterfactuals that eight SLURM array tasks generated hours
             earlier. Generation is ~29h at n_eval=200 and the metrics on top
             are minutes, so decoupling them is what lets the eval finish
             inside the 24h partition cap at all, and lets a metric fix be
             re-run without regenerating anything.
             All four or none — a partial set is a caller bug (scoring
             supplied counterfactuals against freshly scanned originals would
             silently pair the wrong images) and raises.
             `dataset` and `classifier` are then only used for scoring, and
             `generator` / the policies are not used at all.

    Returns
    -------
    dict with all metric values, also printed to stdout and saved as JSON.
    """
    from scipy import stats as scipy_stats
    from src.inference import EVAL_PN_SEED_OFFSET, generate_batch_with_policy

    print("\n" + "=" * 70)
    print("EVALUATION — Singla et al. (2022) metrics")
    if policy_n_to_p is not None or policy_p_to_n is not None:
        print("  (using PPO-guided generation)")
    else:
        print("  (using generator defaults — no trained policy supplied)")
    print("=" * 70)

    # ── try to find heart channel ──────────────────────────────────────────────
    heart_channel_idx = None
    if hasattr(seg_net, "targets"):
        for name in ("Heart", "heart", "Mediastinum"):
            if name in seg_net.targets:
                heart_channel_idx = seg_net.targets.index(name)
                break
    if heart_channel_idx is None:
        print("[metrics] WARNING: heart channel not found in seg_net.targets — CTR will be skipped")

    precomputed = [xn_list, xp_list, xc_np, xc_pn]
    if any(v is not None for v in precomputed) and not all(v is not None for v in precomputed):
        raise ValueError(
            "run_full_evaluation: xn_list/xp_list/xc_np/xc_pn must be supplied "
            "all together or not at all — a partial set would pair scanned "
            "originals against unrelated counterfactuals. Got: "
            + ", ".join(
                f"{n}={'set' if v is not None else 'None'}"
                for n, v in zip(("xn_list", "xp_list", "xc_np", "xc_pn"), precomputed)
            )
        )

    if all(v is not None for v in precomputed):
        # ── precomputed path (eval_main.py --stage reduce) ────────────────────
        print(f"[metrics] using PRECOMPUTED counterfactuals — skipping scan and "
              f"generation. Xn={len(xn_list)}  Xp={len(xp_list)}")
        if not (len(xn_list) == len(xc_np) and len(xp_list) == len(xc_pn)):
            raise ValueError(
                f"precomputed group/counterfactual lengths disagree: "
                f"Xn={len(xn_list)} Xc_n→p={len(xc_np)} | "
                f"Xp={len(xp_list)} Xc_p→n={len(xc_pn)}"
            )
    else:
        # ── scan dataset for Xn / Xp ──────────────────────────────────────────
        xn_list, xn_idx, xp_list, xp_idx = scan_groups(
            dataset, classifier, n_eval, device, allowed_indices=allowed_indices,
        )

        # ── generate counterfactuals ──────────────────────────────────────────
        print("[metrics] generating Xc (n→p) and Xc (p→n) ...")

        def _generate_batch(
            x_list: list, target_c: float, directional_policy,
            index_offset: int, label: str,
        ) -> list[torch.Tensor]:
            if directional_policy is not None:
                return generate_batch_with_policy(
                    x_list, directional_policy,
                    deterministic=deterministic_policy,
                    index_offset=index_offset, label=label, progress_every=10,
                )
            # fallback: direct generator call with default schedule
            cfs = []
            for x in x_list:
                xc, _ = generator.generate_counterfactual(x.to(device), target_c, M=1)
                cfs.append(xc.detach().cpu())
            return cfs

        # index_offset values must match eval_main.py's sharded generate stage,
        # so a single-process run and a sharded one produce identical images.
        xc_np = _generate_batch(xn_list, 1.0, policy_n_to_p, 0, "n_to_p")
        xc_pn = _generate_batch(xp_list, 0.0, policy_p_to_n,
                                EVAL_PN_SEED_OFFSET, "p_to_n")
        if hasattr(generator, "cam_degeneracy_summary"):
            print(generator.cam_degeneracy_summary())

    if len(xn_list) < 200 or len(xp_list) < 200:
        print(f"[metrics] WARNING: group size < 200 — FID estimate will have "
              f"high variance and likely be biased upward. Consider lowering "
              f"the f(x)<0.2 / f(x)>0.8 thresholds or increasing n_eval.")

    # ── classifier scores ──────────────────────────────────────────────────────
    f_xn    = score_batch(xn_list, classifier, device)
    f_xp    = score_batch(xp_list, classifier, device)
    f_xc_np = score_batch(xc_np,   classifier, device)
    f_xc_pn = score_batch(xc_pn,   classifier, device)

    # ── CV ────────────────────────────────────────────────────────────────────
    cv_np = counterfactual_validity(f_xn, f_xc_np, target="positive", tau=tau_cv)
    cv_pn = counterfactual_validity(f_xp, f_xc_pn, target="negative", tau=tau_cv)
    cv    = (cv_np + cv_pn) / 2.0

    # ── FID ───────────────────────────────────────────────────────────────────
    print("[metrics] computing FID ...")
    fid_extractor = (
        _XRVFeatureExtractor(device) if fid_backbone == "xrv"
        else _InceptionFeatureExtractor(device)
    )
    # SAME-group FID: counterfactual vs its SOURCE class. A large value here is
    # ambiguous — it could mean the class genuinely changed, or that the
    # counterfactual is off-manifold. Kept for continuity with earlier runs.
    fid_neg = frechet_inception_distance(xn_list, xc_np, device=device, extractor=fid_extractor)
    fid_pos = frechet_inception_distance(xp_list, xc_pn, device=device, extractor=fid_extractor)

    # CROSS-group FID: counterfactual vs its TARGET class. This is the actual
    # realism test — an n→p counterfactual should be indistinguishable from
    # REAL positives, so LOW is good and the ambiguity above disappears.
    # Reading the two together separates the cases: high same-group + low
    # cross-group is a real class change; high on BOTH is an off-manifold edit,
    # which is what a tiny pixel change producing a huge feature-space shift
    # (v1: MAE 0.036 with FID 103.8) looks like.
    fid_np_vs_real_pos = frechet_inception_distance(
        xp_list, xc_np, device=device, extractor=fid_extractor
    )
    fid_pn_vs_real_neg = frechet_inception_distance(
        xn_list, xc_pn, device=device, extractor=fid_extractor
    )

    # ── FOP ───────────────────────────────────────────────────────────────────
    print("[metrics] computing FOP (TorchXRayVision Support Devices detector) ...")
    fo_detector = _XRVSupportDeviceDetector(device, weights="densenet121-res224-chex")
    fop_np = foreign_object_preservation(fo_detector, xn_list, xc_np, fo_threshold, device)
    fop_pn = foreign_object_preservation(fo_detector, xp_list, xc_pn, fo_threshold, device)
    # fop_* are None when the detector has no Support-Devices head (xrv
    # classifiers don't) -> FOP is skipped rather than averaged.
    fop = (fop_np + fop_pn) / 2.0 if (fop_np is not None and fop_pn is not None) else None

    # ── IP (model-free identity/detail preservation — FOP replacement) ─────────
    print("[metrics] computing IP (MS-SSIM + high-freq detail preservation) ...")
    ip_np = identity_preservation(xn_list, xc_np, device)
    ip_pn = identity_preservation(xp_list, xc_pn, device)

    # ── Edit concentration (model-free locality check) ────────────────────────
    print("[metrics] computing edit concentration ...")
    ec_np = edit_concentration(xn_list, xc_np)
    ec_pn = edit_concentration(xp_list, xc_pn)

    # ── CTR ───────────────────────────────────────────────────────────────────
    # CTR is a CARDIOMEGALY measure and SCP a PLEURAL EFFUSION one; neither says
    # anything about, say, a lung nodule. `clinical_metrics` comes from the
    # active DomainProfile (domains/base.py) so a domain that has no use for
    # them omits them entirely instead of publishing numbers that look like
    # findings. Default keeps the pneumonia domain's behaviour unchanged.
    ctr_results = {}
    if "CTR" in clinical_metrics and heart_channel_idx is not None:
        print("[metrics] computing CTR ...")
        def _ctr_batch(x_list):
            return compute_ctr_batch(
                x_list, seg_net, lung_channel_idx, heart_channel_idx, device
            )
        ctr_xn    = np.array(_ctr_batch(xn_list))
        ctr_xp    = np.array(_ctr_batch(xp_list))
        ctr_xc_np = np.array(_ctr_batch(xc_np))
        ctr_xc_pn = np.array(_ctr_batch(xc_pn))

        # remove NaNs
        mask_n = ~np.isnan(ctr_xn) & ~np.isnan(ctr_xc_np)
        mask_p = ~np.isnan(ctr_xp) & ~np.isnan(ctr_xc_pn)

        delta_n = ctr_xn[mask_n] - ctr_xc_np[mask_n]   # Xn - Xc_n→p
        delta_p = ctr_xp[mask_p] - ctr_xc_pn[mask_p]   # Xp - Xc_p→n
        t_n, p_n = scipy_stats.ttest_rel(ctr_xn[mask_n], ctr_xc_np[mask_n])
        t_p, p_p = scipy_stats.ttest_rel(ctr_xp[mask_p], ctr_xc_pn[mask_p])

        ctr_results = dict(
            mean_xn=float(np.nanmean(ctr_xn)),       std_xn=float(np.nanstd(ctr_xn)),
            mean_xp=float(np.nanmean(ctr_xp)),       std_xp=float(np.nanstd(ctr_xp)),
            mean_xc_np=float(np.nanmean(ctr_xc_np)), std_xc_np=float(np.nanstd(ctr_xc_np)),
            mean_xc_pn=float(np.nanmean(ctr_xc_pn)), std_xc_pn=float(np.nanstd(ctr_xc_pn)),
            mean_delta_n=float(delta_n.mean()),       std_delta_n=float(delta_n.std()),
            t_n=float(t_n), p_n=float(p_n),
            mean_delta_p=float(delta_p.mean()),       std_delta_p=float(delta_p.std()),
            t_p=float(t_p), p_p=float(p_p),
        )

    # ── SCP ───────────────────────────────────────────────────────────────────
    scp_results = {}
    if "SCP" in clinical_metrics:
        print("[metrics] computing SCP ...")

        def _scp_batch(x_list):
            return compute_scp_batch(x_list, obj_det, device)

        scp_xn    = np.array(_scp_batch(xn_list))
        scp_xp    = np.array(_scp_batch(xp_list))
        scp_xc_np = np.array(_scp_batch(xc_np))
        scp_xc_pn = np.array(_scp_batch(xc_pn))

        delta_sn = scp_xn - scp_xc_np
        delta_sp = scp_xp - scp_xc_pn
        t_sn, p_sn = scipy_stats.ttest_rel(scp_xn, scp_xc_np)
        t_sp, p_sp = scipy_stats.ttest_rel(scp_xp, scp_xc_pn)

        # DEGENERACY CHECK. compute_scp is a proxy — sigmoid(-‖yolo_feat‖ / 50)
        # on the lower third of the image — and in practice it saturates: the
        # previous run measured std 0.0008 on a mean of 0.479 across all four
        # groups, i.e. the metric is a constant and its t-tests are testing
        # numerical noise. Flagged rather than silently reported, so a p-value
        # from a constant is never mistaken for a clinical finding. If this
        # fires, either fix the proxy (a real CP-recess detector) or drop SCP
        # from the writeup — a domain can drop it via DomainProfile.
        scp_spread = float(
            max(scp_xn.std(), scp_xp.std(), scp_xc_np.std(), scp_xc_pn.std())
        )
        scp_scale = float(abs(np.mean([scp_xn.mean(), scp_xp.mean()])) + 1e-8)
        scp_degenerate = bool(scp_spread / scp_scale < 0.02)  # <2% rel. spread

        scp_results = dict(
            mean_xn=float(scp_xn.mean()),       std_xn=float(scp_xn.std()),
            mean_xp=float(scp_xp.mean()),       std_xp=float(scp_xp.std()),
            mean_xc_np=float(scp_xc_np.mean()), std_xc_np=float(scp_xc_np.std()),
            mean_xc_pn=float(scp_xc_pn.mean()), std_xc_pn=float(scp_xc_pn.std()),
            mean_delta_n=float(delta_sn.mean()), std_delta_n=float(delta_sn.std()),
            t_n=float(t_sn), p_n=float(p_sn),
            mean_delta_p=float(delta_sp.mean()), std_delta_p=float(delta_sp.std()),
            t_p=float(t_sp), p_p=float(p_sp),
            degenerate=scp_degenerate,
            relative_spread=float(scp_spread / scp_scale),
        )

    # ── LHR — ground-truth localisation ───────────────────────────────────────
    # p→n ONLY. The source images there are POSITIVE, so a radiologist drew a
    # box on them and "did the edit go where the finding is" has an answer. The
    # n→p source images are negative and carry no annotation, so there is no
    # ground truth for where a synthesized opacity belongs — reported as
    # not-applicable rather than as a number, because inventing a target here
    # would defeat the point of having one metric no model can be fooled into
    # agreeing with. See lesion_hit_rate.
    print("[metrics] computing LHR (lesion hit rate, p→n) ...")
    lhr_pn = lesion_hit_rate(xp_list, xc_pn, xp_idx, dataset)

    # ── assemble results dict ─────────────────────────────────────────────────
    results = dict(
        CV=dict(n_to_p=cv_np, p_to_n=cv_pn, mean=cv),
        FID=dict(
            # vs SOURCE class (ambiguous — see the comment at the call site)
            negative_group=fid_neg, positive_group=fid_pos,
            # vs TARGET class (the realism test; lower is better)
            n_to_p_vs_real_positive=fid_np_vs_real_pos,
            p_to_n_vs_real_negative=fid_pn_vs_real_neg,
        ),
        FOP=dict(n_to_p=fop_np, p_to_n=fop_pn, mean=fop),
        IP=dict(n_to_p=ip_np, p_to_n=ip_pn),
        EditConcentration=dict(n_to_p=ec_np, p_to_n=ec_pn),
        LHR=dict(
            p_to_n=lhr_pn,
            n_to_p={
                "_omitted": "not defined for this direction — the n→p source "
                            "images are classifier-negative and carry no lesion "
                            "annotation, so there is no ground truth for where a "
                            "synthesized opacity should appear"
            },
        ),
        CTR=ctr_results,
        SCP=scp_results,
    )

    _print_results(results)
    _save_results(results, ckpt_dir)
    return results


