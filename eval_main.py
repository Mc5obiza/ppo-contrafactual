SHARD_GLOB = "cf_shard_*.pt"


# ─────────────────────────────────────────────────────────────────────────────
# Sharding helpers
# ─────────────────────────────────────────────────────────────────────────────

def _shard_slice(n: int, shard: int, num_shards: int) -> tuple[int, int]:
    """
    Contiguous [lo, hi) slice of `n` items for `shard` of `num_shards`.

    Uses the round-down form so the slices exactly tile [0, n) for any n,
    including n not divisible by num_shards — a gap or overlap here would show
    up as a silently short or double-counted Xn/Xp in the reduce stage.
    """
    if not 0 <= shard < num_shards:
        raise ValueError(f"shard {shard} out of range for num_shards={num_shards}")
    return (shard * n) // num_shards, ((shard + 1) * n) // num_shards


def _shard_path(shard_dir: str, shard: int) -> str:
    return os.path.join(shard_dir, f"cf_shard_{shard:03d}.pt")


# ─────────────────────────────────────────────────────────────────────────────
# Query-image selection for the bidirectional diff plot
# ─────────────────────────────────────────────────────────────────────────────

def _pick_query_images(
    dataset,
    classifier,
    device: str,
    low: float = 0.2,
    high: float = 0.8,
    scan_batch_size: int = 32,
) -> tuple[torch.Tensor, torch.Tensor]:
    """
    Scan the dataset for the first confidently-negative image (f(x) < low)
    and first confidently-positive image (f(x) > high), matching the same
    grouping criteria used in metrics.run_full_evaluation, so the images
    used for the visual diff plot are representative of the Xn / Xp groups
    the quantitative metrics are actually computed over.

    Only used by --stage all. The reduce stage takes xn[0] / xp[0] straight
    from the shards instead — those come from metrics.scan_groups with the
    identical 0.2/0.8 thresholds, so a second full-dataset scan here would be
    duplicated work for the same answer.

    Returns
    -------
    (x_neg, x_pos) : each (1, 1, H, W) on `device`
    """
    from torch.utils.data import DataLoader

    loader = DataLoader(dataset, batch_size=scan_batch_size, shuffle=True, num_workers=2)
    to_rgb = lambda t: t.repeat(1, 3, 1, 1) if t.shape[1] == 1 else t

    x_neg = x_pos = None
    with torch.no_grad():
        for x_batch, _labels in loader:
            x_batch = x_batch.to(device)
            scores  = classifier(to_rgb(x_batch)).squeeze(-1)
            for i in range(len(x_batch)):
                s = scores[i].item()
                if x_neg is None and s < low:
                    x_neg = x_batch[i].unsqueeze(0).clone()
                if x_pos is None and s > high:
                    x_pos = x_batch[i].unsqueeze(0).clone()
            if x_neg is not None and x_pos is not None:
                break

    if x_neg is None or x_pos is None:
        raise RuntimeError(
            f"[eval] could not find both a negative (f(x)<{low}) and "
            f"positive (f(x)>{high}) example for the diff plot — dataset "
            f"may be too small or classifier scores too concentrated. "
            f"found_neg={x_neg is not None}, found_pos={x_pos is not None}"
        )

    return x_neg, x_pos


# ─────────────────────────────────────────────────────────────────────────────
# Shared setup
# ─────────────────────────────────────────────────────────────────────────────

def _build_pipeline():
    """build_common + restore the fine-tuned generator and both policies."""
    ctx = build_common()

    print("\n" + "=" * 70)
    print("STEP 4 — Restoring trained checkpoints")
    print("=" * 70)
    load_generator_weights(ctx.generator, ckpt_dir=config.CKPT_DIR)

    policy_n_to_p = load_directional_policy(
        target_c=1.0, label="n_to_p", ctx=ctx, ckpt_dir=config.CKPT_DIR
    )
    policy_p_to_n = load_directional_policy(
        target_c=0.0, label="p_to_n", ctx=ctx, ckpt_dir=config.CKPT_DIR
    )
    return ctx, policy_n_to_p, policy_p_to_n


def _print_metric_summary(eval_results: dict) -> None:
    print(
        f"Evaluation metrics: "
        f"CV={eval_results['CV']['mean']:.4f} "
        f"(n→p={eval_results['CV']['n_to_p']:.4f}, p→n={eval_results['CV']['p_to_n']:.4f}) | "
        f"FID_neg={eval_results['FID']['negative_group']:.4f} | "
        f"FID_pos={eval_results['FID']['positive_group']:.4f}"
    )
    _ip = eval_results.get('IP')
    if _ip:
        _g = lambda d, k: f"{d[k]:.4f}" if d and d.get(k) is not None else "N/A"
        print(
            f"Identity Preservation (IP): "
            f"n→p MS-SSIM={_g(_ip['n_to_p'], 'ms_ssim')}/HF={_g(_ip['n_to_p'], 'hf_corr')} | "
            f"p→n MS-SSIM={_g(_ip['p_to_n'], 'ms_ssim')}/HF={_g(_ip['p_to_n'], 'hf_corr')}"
        )


def _plot_diffs(x_neg, x_pos, ctx, policy_n_to_p, policy_p_to_n) -> None:
    print("\n" + "=" * 70)
    print("STEP 6B — Counterfactual diff plots (n→p and p→n, PPO-guided)")
    print("=" * 70)
    os.makedirs(config.CKPT_DIR, exist_ok=True)
    generate_and_plot_diff_bidirectional(
        x_neg=x_neg,
        x_pos=x_pos,
        generator=ctx.generator,
        classifier=ctx.classifier,
        save_dir=config.CKPT_DIR,
        directional_policy_n_to_p=policy_n_to_p,
        directional_policy_p_to_n=policy_p_to_n,
        deterministic_policy=True,
    )
    print(
        f"[eval] saved: "
        f"{os.path.join(config.CKPT_DIR, 'counterfactual_diff_n_to_p.png')}, "
        f"{os.path.join(config.CKPT_DIR, 'counterfactual_diff_p_to_n.png')}"
    )


# ─────────────────────────────────────────────────────────────────────────────
# Stage: generate  (one SLURM array task per shard)
# ─────────────────────────────────────────────────────────────────────────────

def stage_generate(args) -> None:
    ctx, policy_n_to_p, policy_p_to_n = _build_pipeline()

    print("\n" + "=" * 70)
    print(f"STAGE GENERATE — shard {args.shard}/{args.num_shards}")
    print("=" * 70)

    # Every shard runs the full scan and then takes its own slice. The scan is
    # a few minutes against a multi-hour generation, and having each shard
    # derive the split itself (rather than one task computing it and the
    # others trusting a file) means there is no ordering dependency between
    # array tasks — any subset can run, in any order, on any node.
    xn_list, xp_list = scan_groups(
        ctx.dataset, ctx.classifier, args.n_eval, config.DEVICE, tag="eval"
    )

    n_lo, n_hi = _shard_slice(len(xn_list), args.shard, args.num_shards)
    p_lo, p_hi = _shard_slice(len(xp_list), args.shard, args.num_shards)
    xn_shard, xp_shard = xn_list[n_lo:n_hi], xp_list[p_lo:p_hi]
    print(f"[eval] shard slice: Xn[{n_lo}:{n_hi}] ({len(xn_shard)} imgs), "
          f"Xp[{p_lo}:{p_hi}] ({len(xp_shard)} imgs)")

    # index_offset makes each image's noise a function of its GLOBAL index, so
    # this shard's output is identical to what a single-process run would have
    # produced for the same images. EVAL_PN_SEED_OFFSET keeps the two
    # directions in disjoint seed space.
    print("[eval] generating Xc (n→p) — this is the expensive part ...")
    xc_np = generate_batch_with_policy(
        xn_shard, policy_n_to_p, deterministic=True,
        index_offset=n_lo, label=f"shard{args.shard} n_to_p",
    )
    print("[eval] generating Xc (p→n) ...")
    xc_pn = generate_batch_with_policy(
        xp_shard, policy_p_to_n, deterministic=True,
        index_offset=EVAL_PN_SEED_OFFSET + p_lo, label=f"shard{args.shard} p_to_n",
    )
    print(ctx.generator.cam_degeneracy_summary())

    os.makedirs(args.shard_dir, exist_ok=True)
    path = _shard_path(args.shard_dir, args.shard)
    torch.save(
        {
            "shard": args.shard,
            "num_shards": args.num_shards,
            "n_eval": args.n_eval,
            "n_slice": [n_lo, n_hi],
            "p_slice": [p_lo, p_hi],
            "xn": torch.cat(xn_shard) if xn_shard else torch.empty(0),
            "xp": torch.cat(xp_shard) if xp_shard else torch.empty(0),
            "xc_np": torch.cat(xc_np) if xc_np else torch.empty(0),
            "xc_pn": torch.cat(xc_pn) if xc_pn else torch.empty(0),
            "config": current_cfg_stamp(),
        },
        path,
    )
    print(f"\n✓ shard {args.shard} written to '{path}'")
    print(f"  Run the reduce stage once ALL {args.num_shards} shards exist:")
    print(f"    python -u eval_main.py --stage reduce --num-shards {args.num_shards}")


# ─────────────────────────────────────────────────────────────────────────────
# Stage: reduce  (one cheap job, after the array finishes)
# ─────────────────────────────────────────────────────────────────────────────

def _load_shards(shard_dir: str, num_shards: int | None):
    """
    Load and concatenate every shard, refusing anything that would silently
    change the metrics.

    Every check here is fatal on purpose. A missing shard would just make Xn/Xp
    shorter, and FID's bias grows sharply as N falls (see
    frechet_inception_distance's docstring) — so a partial reduce would emit a
    plausible-looking but wrong number rather than an error. Same for a config
    mismatch: mixing counterfactuals from two ablation arms produces a metric
    that describes neither.
    """
    found = sorted(glob.glob(os.path.join(shard_dir, SHARD_GLOB)))
    if not found:
        raise FileNotFoundError(
            f"no shards matching '{SHARD_GLOB}' in '{shard_dir}'. Run the "
            f"generate stage first:\n"
            f"    sbatch run_eval_cf.slurm"
        )

    blobs = {}
    for path in found:
        m = re.search(r"cf_shard_(\d+)\.pt$", path)
        if not m:
            continue
        blob = torch.load(path, map_location="cpu")
        blobs[int(m.group(1))] = blob

    declared = {b["num_shards"] for b in blobs.values()}
    if len(declared) != 1:
        raise ValueError(
            f"shards disagree on num_shards: {sorted(declared)}. The shard "
            f"directory mixes runs with different --num-shards; delete "
            f"'{shard_dir}' and regenerate."
        )
    total = declared.pop()
    if num_shards is not None and num_shards != total:
        raise ValueError(
            f"--num-shards {num_shards} but the shards on disk were written "
            f"with --num-shards {total}"
        )

    missing = sorted(set(range(total)) - set(blobs))
    if missing:
        raise FileNotFoundError(
            f"incomplete shard set in '{shard_dir}': have {len(blobs)}/{total}, "
            f"missing shard(s) {missing}. Metrics from a partial set would be "
            f"computed on a short Xn/Xp and are NOT comparable. Re-run just "
            f"the missing tasks:\n"
            f"    sbatch --array={','.join(map(str, missing))} run_eval_cf.slurm"
        )

    n_evals = {b["n_eval"] for b in blobs.values()}
    if len(n_evals) != 1:
        raise ValueError(f"shards disagree on n_eval: {sorted(n_evals)}")

    reference = blobs[0]["config"]
    for k in sorted(blobs):
        if blobs[k]["config"] != reference:
            drift = {
                key: (reference.get(key), blobs[k]["config"].get(key))
                for key in set(reference) | set(blobs[k]["config"])
                if reference.get(key) != blobs[k]["config"].get(key)
            }
            raise ValueError(
                f"shard {k} was generated under a different config than shard 0 "
                f"— these counterfactuals are from different ablation arms and "
                f"must not be pooled. Drift (shard0, shard{k}): {drift}"
            )

    current = current_cfg_stamp()
    if reference != current:
        drift = {
            key: (reference.get(key), current.get(key))
            for key in set(reference) | set(current)
            if reference.get(key) != current.get(key)
        }
        raise ValueError(
            f"the shards were generated under a DIFFERENT config than the one "
            f"currently in config.py. Reporting them now would label one arm's "
            f"counterfactuals as another's. Drift (cached, current): {drift}\n"
            f"Either restore config.py, or delete '{shard_dir}' and regenerate."
        )

    unstack = lambda t: [t[i : i + 1] for i in range(t.shape[0])]
    order = sorted(blobs)
    out = {}
    for key in ("xn", "xp", "xc_np", "xc_pn"):
        out[key] = [img for k in order for img in unstack(blobs[k][key])]

    print(f"[eval] loaded {total} shards from '{shard_dir}' — "
          f"Xn={len(out['xn'])} Xp={len(out['xp'])} "
          f"Xc_n→p={len(out['xc_np'])} Xc_p→n={len(out['xc_pn'])}")
    return out["xn"], out["xp"], out["xc_np"], out["xc_pn"], n_evals.pop()


def stage_reduce(args) -> None:
    xn_list, xp_list, xc_np, xc_pn, n_eval = _load_shards(
        args.shard_dir, args.num_shards
    )

    ctx, policy_n_to_p, policy_p_to_n = _build_pipeline()

    print("\n" + "=" * 70)
    print("STEP 6 — Evaluation (metrics over precomputed counterfactuals)")
    print("=" * 70)
    eval_results = run_full_evaluation(
        dataset=ctx.dataset,
        classifier=ctx.classifier,
        generator=ctx.generator,
        seg_net=ctx.seg_net,
        lung_channel_idx=ctx.lung_channel_idx,
        obj_det=ctx.obj_det,
        n_eval=n_eval,
        ckpt_dir=config.CKPT_DIR,
        device=config.DEVICE,
        policy_n_to_p=policy_n_to_p,
        policy_p_to_n=policy_p_to_n,
        deterministic_policy=True,
        xn_list=xn_list, xp_list=xp_list, xc_np=xc_np, xc_pn=xc_pn,
    )
    _print_metric_summary(eval_results)

    # The shards already hold images that passed the same f(x)<0.2 / f(x)>0.8
    # test _pick_query_images applies, so reuse them instead of rescanning the
    # whole dataset a second time.
    _plot_diffs(
        xn_list[0].to(config.DEVICE), xp_list[0].to(config.DEVICE),
        ctx, policy_n_to_p, policy_p_to_n,
    )
    print("\n✓ Evaluation complete.")


# ─────────────────────────────────────────────────────────────────────────────
# Stage: all  (legacy single-process path — smoke tests only)
# ─────────────────────────────────────────────────────────────────────────────

def stage_all(args) -> None:
    if args.n_eval > 32:
        print(f"\n[eval] WARNING: --stage all with --n-eval {args.n_eval} means "
              f"{2 * args.n_eval} counterfactuals in one process. At the ~4.4 "
              f"min/image measured in job 17665348 that is "
              f"{2 * args.n_eval * 4.4 / 60:.1f}h, and publicgpu caps jobs at "
              f"24h. Use --stage generate as a SLURM array instead.\n")

    ctx, policy_n_to_p, policy_p_to_n = _build_pipeline()

    print("\n" + "=" * 70)
    print("STEP 6 — Evaluation (PPO-guided generation)")
    print("=" * 70)
    eval_results = run_full_evaluation(
        dataset=ctx.dataset,
        classifier=ctx.classifier,
        generator=ctx.generator,
        seg_net=ctx.seg_net,
        lung_channel_idx=ctx.lung_channel_idx,
        obj_det=ctx.obj_det,
        n_eval=min(args.n_eval, len(ctx.dataset)),
        ckpt_dir=config.CKPT_DIR,
        device=config.DEVICE,
        policy_n_to_p=policy_n_to_p,
        policy_p_to_n=policy_p_to_n,
        deterministic_policy=True,
    )
    _print_metric_summary(eval_results)

    x_neg, x_pos = _pick_query_images(
        ctx.dataset, ctx.classifier, device=config.DEVICE, low=0.2, high=0.8
    )
    _plot_diffs(x_neg, x_pos, ctx, policy_n_to_p, policy_p_to_n)
    print("\n✓ Evaluation complete.")


# ─────────────────────────────────────────────────────────────────────────────

def parse_args(argv=None):
    ap = argparse.ArgumentParser(
        description="Evaluation pipeline (Singla et al. 2022 metric suite).",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "typical use:\n"
            "  sbatch run_eval_cf.slurm                      # 8-task array, generates shards\n"
            "  sbatch --dependency=afterok:<id> run_eval_reduce.slurm\n"
            "\n"
            "  python -u eval_main.py --stage all --n-eval 8  # local smoke test\n"
        ),
    )
    ap.add_argument("--stage", choices=("generate", "reduce", "all"), default="all",
                    help="generate: produce one shard of counterfactuals. "
                         "reduce: compute metrics from all shards. "
                         "all: single-process (smoke tests only).")
    ap.add_argument("--shard", type=int, default=None,
                    help="shard index for --stage generate (0-based)")
    ap.add_argument("--num-shards", type=int, default=None,
                    help="total shard count; required for --stage generate, "
                         "optional cross-check for --stage reduce")
    ap.add_argument("--n-eval", dest="n_eval", type=int, default=200,
                    help="images per group (default 200; FID is unstable below this)")
    ap.add_argument("--shard-dir", type=str,
                    default=os.path.join(config.CKPT_DIR, "eval_shards"),
                    help="where cf_shard_*.pt live")
    args = ap.parse_args(argv)

    if args.stage == "generate":
        if args.shard is None or args.num_shards is None:
            ap.error("--stage generate requires both --shard and --num-shards")
        if args.num_shards < 1:
            ap.error("--num-shards must be >= 1")
    return args


def main(argv=None):
    args = parse_args(argv)
    {"generate": stage_generate, "reduce": stage_reduce, "all": stage_all}[args.stage](args)


if __name__ == "__main__":
    main()
