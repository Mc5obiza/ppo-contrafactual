"""
eval_main.py
============
EVALUATION pipeline (Steps 6 and 6B), split out of main.py:
    1-3. Ingest dataset, load pretrained models, build generator
         (shared with training via pipeline.build_common)
    4.   Reload the fine-tuned generator weights + both trained PPO
         policies from checkpoints/
    6.   Full metric suite (Singla et al. 2022): CV / FID / FOP / IP /
         CTR / SCP, generated by stepping the trained policies
    6B.  Counterfactual diff plots, n→p and p→n

Run this AFTER the training pipeline (main.py / run_ppo.slurm) has
written checkpoints/{n_to_p,p_to_n}/ppo_policy.pt.

WHY THIS IS A SEPARATE ENTRY POINT
----------------------------------
PPO training is ~12-20h on the GPUs this job lands on. Running training and
evaluation in one process means a walltime cut during evaluation discards the
finished policies — job 17644171 saved both policies (22:21 and 11:05) and was
then killed at the 24h boundary mid-evaluation, producing no metrics.

WHY EVALUATION IS ITSELF SHARDED
--------------------------------
Splitting eval out was not enough. Eval job 17665348 was cancelled at its own
12h walltime, again with no metrics: it managed ~4.4 min per image, and the
suite generates 400 counterfactuals (Xn=200 + Xp=200), so generation alone
needs ~29h. `sinfo -p publicgpu` caps TIMELIMIT at 24h, so NO walltime value
can make a single-process eval fit — this is a hard partition limit, not a
tuning problem.

Generation is embarrassingly parallel across images and the metrics on top of
it take minutes, so the two are now separate stages:

    --stage generate --shard K --num-shards N
        Generates this shard's slice of Xn/Xp and writes
        {shard_dir}/cf_shard_{K}.pt. Run as a SLURM array
        (run_eval_cf.slurm). ~50 images per shard at N=8, ~2-4h.

    --stage reduce
        Loads every shard, checks they agree, and computes the whole metric
        suite plus the diff plots. Minutes. (run_eval_reduce.slurm)

    --stage all
        The old single-process behaviour. Fine for --n-eval smoke tests,
        cannot finish at --n-eval 200.

Because counterfactuals are cached on disk, a metric bug is now a re-run of
the reduce stage rather than a regeneration.

REPRODUCIBILITY
---------------
The sharded and single-process paths produce byte-identical counterfactuals.
Two things make that true, and both must hold:
  * metrics.scan_groups is deterministic (shuffle=False over a dataset whose
    order is a sorted groupby on patientId) — every process derives the same
    Xn/Xp lists;
  * inference.generate_batch_with_policy seeds per image from its GLOBAL
    index, so an image's noise does not depend on how the work was chunked.
Verify with: --stage all --n-eval 8 vs. two --num-shards 2 shards + reduce.

NOTE ON FOP: both previous runs reported FOP as N/A because the
'Support Devices' head is absent from the densenet121-res224-chex weights
metrics.py requests. That is a pre-existing gap, unrelated to this split —
IP (MS-SSIM + high-frequency correlation) is the model-free stand-in.
"""

